export interface ParsedCodeConnect {
  component: string;
  url: string;
  fileKey?: string;
  nodeId?: string;
  props: Record<string, PropMapping & { kind: "enum" | "boolean" | "string" | "instance" | "children" }>;
}

/** A JS string literal at `i` ("…", '…', `…` without ${}): its value and where it ends. */
function readString(src: string, i: number): { value: string; end: number } | null {
  const quote = src[i];
  if (quote !== '"' && quote !== "'" && quote !== "`") return null;
  let out = "";
  for (let k = i + 1; k < src.length; k++) {
    const c = src[k]!;
    if (c === "\\") {
      const n = src[k + 1];
      out += n === "n" ? "\n" : n === "t" ? "\t" : (n ?? "");
      k++;
      continue;
    }
    if (quote === "`" && c === "$" && src[k + 1] === "{") return null; // template with code: not a literal
    // A quote or apostrophe string ends at its line: an apostrophe in a
    // comment ("Figma's size") must not run on and swallow the next lines.
    if (quote !== "`" && (c === "\n" || c === "\r")) return null;
    if (c === quote) return { value: out, end: k + 1 };
    out += c;
  }
  return null;
}

/** If a comment starts at `i`, the index just past it; else `i`. */
function commentEnd(src: string, i: number): number {
  if (src.startsWith("//", i)) {
    const nl = src.indexOf("\n", i);
    return nl < 0 ? src.length : nl;
  }
  if (src.startsWith("/*", i)) {
    const close = src.indexOf("*/", i + 2);
    return close < 0 ? src.length : close + 2;
  }
  return i;
}

/**
 * If a comment, a string or a template literal starts at `i`, the index just
 * past it; else `i`. A template is walked to its closing backtick through
 * every `${ … }` (with their own strings, comments and braces), so a `//` in
 * `https://x/${id}` is never taken for a comment and its braces never count.
 */
function skipNonCode(src: string, i: number): number {
  const ce = commentEnd(src, i);
  if (ce > i) return ce;
  const c = src[i];
  if (c === "`") return skipTemplate(src, i);
  if (c === '"' || c === "'") {
    // Only where an expression can start: after a word (`Don't`, `won't` in
    // JSX text), `)`, `]`, `}` or a regex's `/` a quote is a plain character —
    // two apostrophes on one line must not pair up and hide the code between.
    if (!stringCanStart(src, i)) return i;
    const str = readString(src, i);
    // Unterminated on its line: a plain character too.
    return str ? str.end : i;
  }
  return i;
}

const STRING_AFTER_WORD = new Set(["return", "case", "typeof", "in", "of", "else", "void", "yield", "await", "delete", "throw", "new", "instanceof", "do", "export", "default", "from", "import", "as", "satisfies", "extends", "keyof"]);

/** Can a string literal start at `i` (judged by what comes before it)? */
function stringCanStart(src: string, i: number): boolean {
  let k = i - 1;
  while (k >= 0 && /\s/.test(src[k]!)) k--;
  if (k < 0) return true;
  const p = src[k]!;
  if (/[\w$]/.test(p)) {
    let w = k;
    while (w >= 0 && /[\w$]/.test(src[w]!)) w--;
    if (!STRING_AFTER_WORD.has(src.slice(w + 1, k + 1))) return false;
    // A keyword in PROSE ("Best of '90s" in JSX text) follows another word or
    // a tag's `>`; a real `return 'x'` / `case 'a'` follows code punctuation.
    let q = w;
    while (q >= 0 && /[ \t]/.test(src[q]!)) q--;
    return q < 0 || !/[\w$>]/.test(src[q]!);
  }
  // `>` closes a JSX tag (`<p>'Tis`) — text follows; only `=>` starts an expression.
  if (p === ">") return src[k - 1] === "=";
  return "([{,=:;?!&|+-*%<~^".includes(p);
}

function skipTemplate(src: string, i: number): number {
  for (let k = i + 1; k < src.length; k++) {
    const c = src[k];
    if (c === "\\") {
      k++;
      continue;
    }
    if (c === "`") return k + 1;
    if (c === "$" && src[k + 1] === "{") k = skipBlock(src, k + 1) - 1;
  }
  return src.length;
}

/** From the `{` at `open`, the index just past its partner `}` — code-aware. */
function skipBlock(src: string, open: number): number {
  let depth = 0;
  for (let k = open; k < src.length; k++) {
    const past = skipNonCode(src, k);
    if (past > k) {
      k = past - 1;
      continue;
    }
    if (src[k] === "{") depth++;
    else if (src[k] === "}" && --depth === 0) return k + 1;
  }
  return src.length;
}

/**
 * The first match of `re` that starts in CODE (not in a comment, string or
 * template) and at a word start (`props:` does not match inside `ownprops:`).
 */
function searchCode(src: string, re: RegExp): number {
  for (let i = 0; i < src.length; i++) {
    const past = skipNonCode(src, i);
    if (past > i) {
      i = past - 1;
      continue;
    }
    if (/[\w$]/.test(src[i - 1] ?? "")) continue;
    if (re.test(src.slice(i, i + 80))) return i;
  }
  return -1;
}

/**
 * Offsets of `figma.connect(` that are CODE — not inside a comment or a
 * string (a commented-out connection must not come back to life).
 */
function connectCalls(src: string): number[] {
  const out: number[] = [];
  for (let i = 0; i < src.length; i++) {
    const past = skipNonCode(src, i);
    if (past > i) {
      i = past - 1;
      continue;
    }
    if (src.startsWith("figma.connect(", i) && !/[\w$.]/.test(src[i - 1] ?? "")) out.push(i);
  }
  return out;
}

/** A bare identifier at `i` (an unquoted object key). */
function readIdent(src: string, i: number): { value: string; end: number } | null {
  const m = /^[A-Za-z_$][\w$]*/.exec(src.slice(i));
  return m ? { value: m[0], end: i + m[0].length } : null;
}

function skipWs(src: string, i: number): number {
  while (i < src.length) {
    if (/\s/.test(src[i]!)) i++;
    else if (src.startsWith("//", i)) i = src.indexOf("\n", i) < 0 ? src.length : src.indexOf("\n", i);
    else if (src.startsWith("/*", i)) i = src.indexOf("*/", i) < 0 ? src.length : src.indexOf("*/", i) + 2;
    else break;
  }
  return i;
}

/** The text between the brace at `open` and its partner, skipping braces inside strings. */
function braced(src: string, open: number): string {
  let depth = 0;
  for (let i = open; i < src.length; i++) {
    const c = src[i];
    const past = skipNonCode(src, i);
    if (past > i) {
      i = past - 1;
      continue;
    }
    if (c === "{") depth++;
    else if (c === "}") {
      depth--;
      if (depth === 0) return src.slice(open + 1, i);
    }
  }
  return src.slice(open + 1);
}

/** fileKey + node id from any Figma URL shape (design/file/proto/board, `1-2`, `1:2`, `1%3A2`). */
export function parseConnectUrl(url: string): { fileKey: string; nodeId: string } | null {
  let u = url;
  try {
    u = decodeURIComponent(url);
  } catch {
    /* keep raw */
  }
  const m = /figma\.com\/(?:design|file|proto|board)\/([A-Za-z0-9]+)[^?#]*[?#](?:.*&)?node-id=([0-9]+)[-:]([0-9]+)/.exec(u);
  return m ? { fileKey: m[1]!, nodeId: `${m[2]}:${m[3]}` } : null;
}

type PropKind = ParsedCodeConnect["props"][string]["kind"];

/** Entries of a `props: { … }` body. Unrecognised entries are named in `skipped`. */
function parseProps(body: string, component: string, skipped: string[]): ParsedCodeConnect["props"] {
  const props: ParsedCodeConnect["props"] = {};
  let i = 0;
  while ((i = skipWs(body, i)) < body.length) {
    // key
    let key: string | null = null;
    const ks = readString(body, i);
    if (ks) {
      key = ks.value;
      i = ks.end;
    } else {
      const km = /^[A-Za-z_$][\w$]*/.exec(body.slice(i));
      if (!km) {
        i++;
        continue;
      }
      key = km[0];
      i += km[0].length;
    }
    i = skipWs(body, i);
    if (body[i] !== ":") {
      i++;
      continue;
    }
    i = skipWs(body, i + 1);
    const call = /^figma\.(enum|boolean|string|instance|children|textContent)\s*\(/.exec(body.slice(i));
    // The value expression ends at the next top-level comma.
    let depth = 0;
    let end = i;
    for (; end < body.length; end++) {
      const c = body[end]!;
      const past = skipNonCode(body, end);
      if (past > end) {
        end = past - 1;
        continue;
      }
      if (c === "(" || c === "{" || c === "[") depth++;
      else if (c === ")" || c === "}" || c === "]") depth--;
      else if (c === "," && depth === 0) break;
    }
    const expr = body.slice(i, end);
    i = end + 1;
    if (!call) {
      skipped.push(`${component}.${key}: "${expr.trim().slice(0, 60)}" is not a figma.enum/boolean/string/instance/children prop — left out.`);
      continue;
    }
    const kind = call[1]!;
    let k = skipWs(expr, call[0].length);
    const nameLit = readString(expr, k);
    if (!nameLit) {
      skipped.push(`${component}.${key}: the Figma property name is not a string literal — left out.`);
      continue;
    }
    const figmaName = nameLit.value;
    if (kind === "children" || key === "children") {
      props[key] = { figma: figmaName, type: "TEXT", kind: "children" };
      continue;
    }
    if (kind === "enum") {
      const values: Record<string, string> = {};
      k = skipWs(expr, nameLit.end);
      if (expr[k] === ",") {
        k = skipWs(expr, k + 1);
        if (expr[k] === "{") {
          const obj = braced(expr, k);
          let j = 0;
          while ((j = skipWs(obj, j)) < obj.length) {
            const fk = readString(obj, j) ?? readIdent(obj, j);
            if (!fk) {
              j++;
              continue;
            }
            j = skipWs(obj, fk.end);
            if (obj[j] !== ":") continue;
            j = skipWs(obj, j + 1);
            const cv = readString(obj, j);
            if (cv) {
              values[cv.value] = fk.value; // Figma value → code value, stored code → Figma
              j = cv.end;
            } else {
              const stop = obj.indexOf(",", j);
              j = stop < 0 ? obj.length : stop;
            }
            j = skipWs(obj, j);
            if (obj[j] === ",") j++;
          }
        }
      }
      props[key] = { figma: figmaName, type: "VARIANT", values, kind: "enum" };
    } else if (kind === "boolean") props[key] = { figma: figmaName, type: "BOOLEAN", kind: "boolean" as PropKind };
    else if (kind === "instance") props[key] = { figma: figmaName, type: "INSTANCE_SWAP", kind: "instance" };
    else props[key] = { figma: figmaName, type: "TEXT", kind: "string" };
  }
  return props;
}

export function parseCodeConnect(source: string): { connections: ParsedCodeConnect[]; skipped: string[] } {
  const connections: ParsedCodeConnect[] = [];
  const skipped: string[] = [];
  const starts: number[] = [];
  starts.push(...connectCalls(source));
  starts.forEach((at, n) => {
    const spanEnd = starts[n + 1] ?? source.length;
    let i = skipWs(source, at + "figma.connect(".length);
    const firstLit = readString(source, i);
    if (firstLit) {
      // `figma.connect("url", {...})` — the HTML/web form: no code component to map.
      skipped.push(`figma.connect("${firstLit.value.slice(0, 60)}", …) names no code component — left out.`);
      return;
    }
    const cm = /^[A-Za-z_$][\w$.]*/.exec(source.slice(i));
    if (!cm) {
      skipped.push(`A figma.connect(…) call at offset ${at} could not be read — left out.`);
      return;
    }
    const component = cm[0];
    i = skipWs(source, i + component.length);
    if (source[i] !== ",") {
      skipped.push(`${component}: figma.connect has no URL argument — left out.`);
      return;
    }
    i = skipWs(source, i + 1);
    const urlLit = readString(source, i);
    if (!urlLit) {
      skipped.push(`${component}: the URL is not a string literal — left out.`);
      return;
    }
    const link = parseConnectUrl(urlLit.value);
    const conn: ParsedCodeConnect = { component, url: urlLit.value, ...(link ? { fileKey: link.fileKey, nodeId: link.nodeId } : {}), props: {} };
    const span = source.slice(urlLit.end, spanEnd);
    // `props:` in CODE: a commented-out `// props: {…}` above the real one must not win.
    const propsAt = searchCode(span, /^props\s*:/);
    if (propsAt >= 0) {
      const open = span.indexOf("{", propsAt);
      if (open >= 0) conn.props = parseProps(braced(span, open), component, skipped);
    }
    if (!link) skipped.push(`${component}: the URL has no node-id — cannot tell which Figma component it is.`);
    connections.push(conn);
  });
  return { connections, skipped };
}

/**
 * Parsed Code Connect → a component map (needs Figma component NAMES, which
 * the files do not hold: `figmaNameByNodeId` supplies them, e.g. from
 * get_nodes). Connections whose node is unknown are left out and listed.
 */
export function codeConnectToMap(connections: ParsedCodeConnect[], figmaNameByNodeId: Record<string, string>): { map: ComponentMap; unresolved: string[]; conflicts: string[] } {
  const components: Record<string, ComponentMapping> = {};
  const unresolved: string[] = [];
  /** One code name connected to two DIFFERENT Figma components: the first is kept, the rest named here. */
  const conflicts: string[] = [];
  for (const c of connections) {
    const figmaName = c.nodeId ? figmaNameByNodeId[c.nodeId] : undefined;
    if (!figmaName) {
      unresolved.push(c.component);
      continue;
    }
    const mapping: ComponentMapping = { figma: figmaName };
    const props: Record<string, PropMapping> = {};
    for (const [code, p] of Object.entries(c.props)) {
      if (p.kind === "children") {
        mapping.children = p.figma;
        continue;
      }
      props[code] = { figma: p.figma, ...(p.type ? { type: p.type } : {}), ...(p.values && Object.keys(p.values).length ? { values: p.values } : {}) };
    }
    if (Object.keys(props).length) mapping.props = props;
    const prev = components[c.component];
    if (prev && prev.figma !== mapping.figma) {
      conflicts.push(`${c.component}: connected to "${prev.figma}" and to "${mapping.figma}" — kept "${prev.figma}".`);
      continue;
    }
    // Several connections for one component (one per variant): merge, never
    // let the last one silently replace the others — down to enum VALUES,
    // where each variant's connection lists only its own subset.
    if (prev) {
      const props: Record<string, PropMapping> = { ...(prev.props ?? {}) };
      for (const [code, p] of Object.entries(mapping.props ?? {})) {
        const old = props[code];
        props[code] = old && old.figma === p.figma ? { ...old, ...p, ...(old.values || p.values ? { values: { ...(old.values ?? {}), ...(p.values ?? {}) } } : {}) } : p;
      }
      components[c.component] = { ...prev, ...(mapping.children ? { children: mapping.children } : {}), ...(Object.keys(props).length ? { props } : {}) };
    } else components[c.component] = mapping;
  }
  return { map: { version: 1, components }, unresolved, conflicts };
}
