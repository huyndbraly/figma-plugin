export interface ParsedCodeConnect {
  component: string;
  url: string;
  fileKey?: string;
  nodeId?: string;
  props: Record<string, PropMapping & { kind: "enum" | "boolean" | "string" | "instance" | "children" }>;
}

function unquote(s: string): string {
  const t = s.trim();
  if ((t.startsWith('"') && t.endsWith('"')) || (t.startsWith("'") && t.endsWith("'")) || (t.startsWith("`") && t.endsWith("`"))) return t.slice(1, -1);
  return t;
}

/** The text between the brace at `open` and its partner. */
function braced(src: string, open: number): string {
  let depth = 0;
  for (let i = open; i < src.length; i++) {
    const c = src[i];
    if (c === "{") depth++;
    else if (c === "}") {
      depth--;
      if (depth === 0) return src.slice(open + 1, i);
    }
  }
  return src.slice(open + 1);
}

export function parseCodeConnect(source: string): { connections: ParsedCodeConnect[]; skipped: string[] } {
  const connections: ParsedCodeConnect[] = [];
  const skipped: string[] = [];
  const re = /figma\.connect\(\s*([A-Za-z_$][\w$.]*)\s*,\s*(["'`])([^"'`]+)\2\s*(?:,\s*\{)?/g;
  let m: RegExpExecArray | null;
  while ((m = re.exec(source))) {
    const component = m[1]!;
    const url = m[3]!;
    const link = /figma\.com\/(?:design|file)\/([A-Za-z0-9]+)[^?]*\?(?:.*&)?node-id=([0-9]+[-:][0-9]+)/.exec(url);
    const conn: ParsedCodeConnect = {
      component,
      url,
      ...(link ? { fileKey: link[1], nodeId: link[2]!.replace("-", ":") } : {}),
      props: {},
    };
    const after = m.index + m[0].length;
    const propsAt = source.indexOf("props:", after);
    const nextConnect = source.indexOf("figma.connect(", after);
    if (propsAt >= 0 && (nextConnect < 0 || propsAt < nextConnect)) {
      const open = source.indexOf("{", propsAt);
      const body = braced(source, open);
      const propRe = /([A-Za-z_$][\w$]*|"[^"]+"|'[^']+')\s*:\s*figma\.(enum|boolean|string|instance|children|textContent)\(\s*(["'`])([^"'`]+)\3\s*(?:,\s*\{([^}]*)\})?/g;
      let pm: RegExpExecArray | null;
      while ((pm = propRe.exec(body))) {
        const code = unquote(pm[1]!);
        const kind = pm[2]!;
        const figmaName = pm[4]!;
        if (kind === "children" || code === "children") {
          conn.props[code] = { figma: figmaName, type: "TEXT", kind: "children" };
          continue;
        }
        if (kind === "enum") {
          const values: Record<string, string> = {};
          for (const pair of (pm[5] ?? "").split(",")) {
            const [k, v] = pair.split(":");
            if (k && v && /["'`]/.test(v)) values[unquote(v)] = unquote(k);
          }
          conn.props[code] = { figma: figmaName, type: "VARIANT", values, kind: "enum" };
        } else if (kind === "boolean") conn.props[code] = { figma: figmaName, type: "BOOLEAN", kind: "boolean" };
        else if (kind === "instance") conn.props[code] = { figma: figmaName, type: "INSTANCE_SWAP", kind: "instance" };
        else conn.props[code] = { figma: figmaName, type: "TEXT", kind: "string" };
      }
    }
    if (!link) skipped.push(`${component}: the URL has no node-id — cannot tell which Figma component it is.`);
    connections.push(conn);
  }
  return { connections, skipped };
}

/**
 * Parsed Code Connect → a component map (needs Figma component NAMES, which
 * the files do not hold: `figmaNameByNodeId` supplies them, e.g. from
 * get_nodes). Connections whose node is unknown are left out and listed.
 */
export function codeConnectToMap(connections: ParsedCodeConnect[], figmaNameByNodeId: Record<string, string>): { map: ComponentMap; unresolved: string[] } {
  const components: Record<string, ComponentMapping> = {};
  const unresolved: string[] = [];
  for (const c of connections) {
    const figmaName = c.nodeId ? figmaNameByNodeId[c.nodeId] : undefined;
    if (!figmaName) {
      unresolved.push(c.component);
      continue;
    }
    const mapping: ComponentMapping = { figma: figmaName };
    const props: Record<string, PropMapping> = {};
    for (const [code, p] of Object.entries(c.props)) {
      if (p.kind === "children") {
        mapping.children = p.figma;
        continue;
      }
      props[code] = { figma: p.figma, ...(p.type ? { type: p.type } : {}), ...(p.values && Object.keys(p.values).length ? { values: p.values } : {}) };
    }
    if (Object.keys(props).length) mapping.props = props;
    components[c.component] = mapping;
  }
  return { map: { version: 1, components }, unresolved };
}
