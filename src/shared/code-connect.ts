/**
 * Code Connect files (`<Component>.figma.tsx`) ↔ the component map.
 *
 * The component map (component-map.ts) says how a code component's props
 * translate to a Figma component's variants and properties. Figma's Code
 * Connect says the same thing in its own format — `figma.connect(Button,
 * url, { props: { size: figma.enum("Size", {...}) }, example })` — and is
 * what Dev Mode shows next to a component. Writing one from the other keeps
 * a single source of truth; reading them back lets an agent that finds Code
 * Connect files in a repo draw with the right variants.
 *
 * Pure: strings in, strings out. The reader is a tolerant scanner for the
 * shape this writer (and the Code Connect CLI's own templates) produce, not a
 * TypeScript parser — what it cannot read it reports in `skipped`.
 */
import type { ComponentMap, ComponentMapping, PropMapping } from "./component-map.js";

export interface CodeConnectTarget {
  /** Code component name (PascalCase), the key of map.components. */
  component: string;
  /** Figma node id of the component / component set ("1:2"). */
  nodeId: string;
}

export interface CodeConnectOptions {
  fileKey: string;
  /** Module the components are imported from, e.g. "@/components" or "../ui". */
  importFrom?: string;
  /** Where each code component lives, overriding importFrom: { Button: "@/ui/button" }. */
  importPaths?: Record<string, string>;
}

export interface CodeConnectFile {
  component: string;
  fileName: string;
  source: string;
}

const IDENT = /^[A-Za-z_$][\w$]*$/;

function q(s: string): string {
  return JSON.stringify(s);
}

function propKey(k: string): string {
  return IDENT.test(k) ? k : q(k);
}

export function figmaNodeUrl(fileKey: string, nodeId: string): string {
  return `https://www.figma.com/design/${fileKey}/?node-id=${nodeId.replace(/:/g, "-")}`;
}

function propExpr(p: PropMapping): string {
  const name = q(p.figma);
  switch (p.type) {
    case "BOOLEAN":
      return `figma.boolean(${name})`;
    case "TEXT":
      return `figma.string(${name})`;
    case "INSTANCE_SWAP":
      return `figma.instance(${name})`;
    default: {
      // VARIANT (or untyped): an enum from Figma values to code values.
      const values = Object.entries(p.values ?? {});
      if (!values.length) return `figma.string(${name})`;
      const body = values.map(([code, fig]) => `${q(fig)}: ${q(code)}`).join(", ");
      return `figma.enum(${name}, { ${body} })`;
    }
  }
}

/** One `.figma.tsx` source for one mapped component. */
export function codeConnectSource(component: string, mapping: ComponentMapping, target: CodeConnectTarget, opts: CodeConnectOptions): string {
  const from = opts.importPaths?.[component] ?? opts.importFrom ?? `./${component}`;
  const props = Object.entries(mapping.props ?? {});
  const lines: string[] = [];
  lines.push(`import figma from "@figma/code-connect";`);
  lines.push(`import { ${component} } from ${q(from)};`);
  lines.push("");
  lines.push(`// Generated by figma-plugin (figma.exportCodeConnect) from the component map.`);
  lines.push(`// Figma component: ${mapping.figma}`);
  lines.push(`figma.connect(${component}, ${q(figmaNodeUrl(opts.fileKey, target.nodeId))}, {`);
  if (props.length || mapping.children) {
    lines.push(`  props: {`);
    for (const [code, p] of props) lines.push(`    ${propKey(code)}: ${propExpr(p)},`);
    if (mapping.children) lines.push(`    children: figma.string(${q(mapping.children)}),`);
    lines.push(`  },`);
  }
  const attrs = props.map(([code]) => (IDENT.test(code) ? ` ${code}={props.${code}}` : ` {...{ ${q(code)}: props[${q(code)}] }}`)).join("");
  const usesProps = props.length > 0 || !!mapping.children;
  const arg = usesProps ? "props" : "()";
  lines.push(
    mapping.children
      ? `  example: (${arg}) => <${component}${attrs}>{props.children}</${component}>,`
      : `  example: (${arg}) => <${component}${attrs} />,`,
  );
  lines.push(`});`);
  return lines.join("\n") + "\n";
}

/**
 * Every mapped component that has a node id → a file. Components with no
 * node id (not found in the file) are returned in `missing`, not guessed.
 */
export function mapToCodeConnect(map: ComponentMap, nodeIdByFigmaName: Record<string, string>, opts: CodeConnectOptions): { files: CodeConnectFile[]; missing: string[] } {
  const files: CodeConnectFile[] = [];
  const missing: string[] = [];
  for (const [component, mapping] of Object.entries(map.components)) {
    const nodeId = nodeIdByFigmaName[mapping.figma];
    if (!nodeId) {
      missing.push(component);
      continue;
    }
    files.push({ component, fileName: `${component}.figma.tsx`, source: codeConnectSource(component, mapping, { component, nodeId }, opts) });
  }
  return { files, missing };
}

